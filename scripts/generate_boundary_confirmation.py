"""Derive the dispatch campaign from CI so real commands cannot silently drift."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / '.github/workflows/boundary-confirmation.yml'
UPLOAD = 'actions/upload-artifact@043fb46d1a93c77aae656e7c1c64a875d1fc6a0a'


def generate():
    source = (ROOT/'.github/workflows/ci.yml').read_text(encoding='utf-8')
    jobs = dict(re.findall(r'^  ([a-z][a-z0-9-]*):\n(.*?)(?=^  [a-z][a-z0-9-]*:|\Z)', source.split('jobs:\n', 1)[1], re.M | re.S))
    output = '''# Generated by scripts/generate_boundary_confirmation.py from ci.yml.
name: Boundary integrated confirmation
on:
  workflow_dispatch:
    inputs:
      expected_sha:
        description: Exact 40-character commit SHA to confirm
        required: true
        type: string
permissions:
  contents: read
  actions: read
env:
  CARGO_BUILD_JOBS: 2
  PLENORA_CONFIRMATION_DIR: ${{ github.workspace }}/target/p25-evidence
jobs:
'''
    output += '  qualification-sha:\n'+jobs['qualification-sha']
    names = []
    for original, name, os_name in [('quality','quality-linux','ubuntu-latest'), ('quality','quality-windows','windows-latest'), ('anti-panic','anti-panic',None), ('nats-integration','nats-integration',None), ('postgres-integration','postgres-integration',None), ('coverage','coverage',None)]:
        names.append(name)
        body = jobs[original]
        if os_name:
            body = re.sub(r'    strategy:.*?(?=    steps:)', '', body, flags=re.S)
            body = body.replace('${{ matrix.os }}', os_name)
        # Exhaustive collection applies to setup, lint, tests and installed surfaces too.
        parts = re.split(r'(?=      - name: )', body)
        for index in range(1, len(parts)):
            part = parts[index]
            if 'Aggregate every campaign outcome' in part:
                continue
            if not re.search(r'^        id:', part, re.M):
                part = part.replace('\n', f'\n        id: confirmation_{index:02}\n', 1)
            if not re.search(r'^        if:', part, re.M):
                part = part.replace('\n', '\n        if: always()\n', 1)
            if 'continue-on-error:' not in part:
                part = part.replace('\n', '\n        continue-on-error: true\n', 1)
            # Continue all Rust test binaries after a failed test binary.
            part = part.replace('cargo test --workspace', 'cargo test --no-fail-fast --workspace')
            if original == 'quality' and part.startswith('      - name: Run tests\n'):
                part = part.replace('cargo test --no-fail-fast --workspace --all-targets --all-features --locked', 'python scripts/run_confirmation_tests.py')
            elif 'cargo test ' in part or ('cargo llvm-cov ' in part and '--no-report' in part):
                label = re.search(r'^        id: (\w+)', part, re.M)[1]
                command = 'cargo test ' if 'cargo test ' in part else 'cargo llvm-cov '
                part = part.replace(command, f'python scripts/run_confirmation_tests.py --label {label} -- '+command)
            parts[index] = part
        body = ''.join(parts)
        # Establish exact source before any receipts; retain checkout action pin from CI.
        body = body.replace('      - name: Install pinned Rust toolchain', '''      - name: Verify checked out SHA
        id: confirmation_sha
        if: always()
        continue-on-error: true
        shell: bash
        env:
          EXPECTED_SHA: ${{ inputs.expected_sha }}
        run: test "$(git rev-parse HEAD)" = "$EXPECTED_SHA"

      - name: Install pinned Rust toolchain''', 1)
        if original == 'coverage':
            body += '''      - name: Export complete coverage data
        id: confirmation_coverage_export
        if: always()
        continue-on-error: true
        run: cargo llvm-cov report --json --output-path target/p25-evidence/coverage.json

'''
        body += '''      - name: Persist original step outcomes
        if: always()
        env:
          CAMPAIGN_STEPS: ${{ toJson(steps) }}
        run: python scripts/boundary_confirmation.py collect --job JOB

      - name: Upload campaign evidence even on failure
        if: always()
        uses: UPLOAD
        with:
          name: p25-input-${{ github.run_attempt }}-JOB
          path: target/p25-evidence
          if-no-files-found: error

'''.replace('JOB', name).replace('UPLOAD', UPLOAD)
        output += '  '+name+':\n'+body
    output += '''  report:
    name: Enumerate executed D proofs and publish one report
    if: always()
    needs: [qualification-sha, NAMES]
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1
      - name: Download all evidence from this run attempt
        id: download
        continue-on-error: true
        env:
          GH_TOKEN: ${{ github.token }}
        run: gh run download "$GITHUB_RUN_ID" --pattern "p25-input-$GITHUB_RUN_ATTEMPT-*" --dir target/p25-evidence
      - name: Require all executed cells and original job outcomes
        if: always()
        env:
          CONFIRMATION_NEEDS: ${{ toJson(needs) }}
        run: python scripts/boundary_confirmation.py report
      - name: Publish unified report and complete evidence
        if: always()
        uses: UPLOAD
        with:
          name: boundary-confirmation-${{ github.sha }}-${{ github.run_attempt }}
          path: target/p25-evidence
          if-no-files-found: error
'''.replace('NAMES', ', '.join(names)).replace('UPLOAD', UPLOAD)
    return output


if __name__ == '__main__':
    OUT.write_text(generate(), encoding='utf-8')
