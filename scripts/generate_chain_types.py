"""Generate the public draft DTOs from the pinned local chain schemas, offline."""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "contracts/chains-v2/schemas"
OUT = ROOT / "crates/plenora-runtime-chain-contracts/src/types.rs"
definitions = {}
names = {}
members = {}


def pascal(text):
    return "".join(part.capitalize() for part in text.replace("-", "_").split("_"))


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def resolve(ref, path):
    file, _, pointer = ref.partition("#")
    target = (path.parent / file).resolve() if file else path
    value = read(target)
    for part in pointer.strip("/").split("/") if pointer else []:
        value = value[part]
    return value, target, pointer


def emit(schema, name, path):
    if "$ref" in schema:
        child, target, pointer = resolve(schema["$ref"], path)
        key = str(target) + pointer
        if key not in names:
            names[key] = ("ChainError" if pointer == "/$defs/error" else pascal(pointer.split("/")[-1])) if pointer else name
        return emit(child, names[key], target)
    if "oneOf" in schema:
        variants = schema["oneOf"]
        if len(variants) == 2 and variants[1].get("type") == "null":
            return "Option<" + emit(variants[0], name, path) + ">"
        if name not in definitions:
            definitions[name] = ""
            fields = [f"    /// Closed alternative {i}.\n    Variant{i}({emit(v, name + str(i), path)})," for i, v in enumerate(variants)]
            members[name] = ("enum", [(f"Variant{i}", emit(v, name + str(i), path)) for i, v in enumerate(variants)])
            definitions[name] = (f"/// Closed union `{name}` from the pinned schema.\n"
                                 "#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(untagged)]\n"
                                 f"pub enum {name} {{\n" + "\n".join(fields) + "\n}\n")
        return name
    kind = schema.get("type")
    if "enum" in schema or "const" in schema:
        sample = schema.get("enum", [schema.get("const")])[0]
        return "bool" if isinstance(sample, bool) else "u64" if isinstance(sample, int) else "String"
    if kind == "object":
        if "properties" not in schema:
            return "BTreeMap<String, " + emit(schema["additionalProperties"], name, path) + ">"
        if name not in definitions:
            definitions[name] = ""
            fields = []
            members[name] = ("struct", [])
            for field, child in schema["properties"].items():
                ty = emit(child, name + pascal(field), path)
                optional = field not in schema.get("required", [])
                if optional:
                    ty = f"Option<{ty}>"
                members[name][1].append((field, ty))
                fields.append(f"    /// Wire field `{field}`; validated by the closed parser.\n" +
                              ('    #[serde(skip_serializing_if = "Option::is_none")]\n' if optional else '') +
                              f"    pub {field}: {ty},")
            definitions[name] = (f"/// Draft `{name}`; construction does not attest admission.\n"
                                 "#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(deny_unknown_fields)]\n"
                                 f"pub struct {name} {{\n" + "\n".join(fields) + "\n}\n")
        return name
    if kind == "array":
        return "Vec<" + emit(schema["items"], name + "Item", path) + ">"
    return {"string": "String", "integer": "u64", "boolean": "bool"}[kind]


def main():
    for file, name in [("chain-plan-v2", "Plan"), ("chain-result-v2", "ChainResult"),
                       ("chain-event-v2", "Event"), ("chain-error-v2", "ChainError"),
                       ("reference-context", "Registry")]:
        path = BASE / (file + ".schema.json")
        emit(read(path), name, path)
    text = ('//! Public draft DTOs. Generated by `scripts/generate_chain_types.py`.\n'
            '//! Only closed parsers decode wire input; construction requires validation.\n'
            'use std::collections::BTreeMap;\nuse serde::Serialize;\n\n')
    for name, definition in definitions.items():
        text += definition.replace(", Deserialize", "")
        text += (f'impl std::fmt::Debug for {name} {{\n'
                 '    fn fmt(&self, f: &mut std::fmt::Formatter<\'_>) -> std::fmt::Result {\n'
                 f'        f.write_str("{name} {{ [redacted] }}")\n    }}\n}}\n\n')
    text += "// Wire field names are fixed by the external contract.\n#[allow(clippy::struct_field_names)]\nmod wire {\nuse std::collections::BTreeMap;\nuse serde::{Deserialize, Serialize};\n"
    text += "\n".join(definitions.values()) + "\n}\n"

    def convert(ty, expr):
        if not set(re.findall(r"[A-Za-z0-9_]+", ty)) & definitions.keys():
            return expr
        if ty.startswith("Option<"):
            if ty[7:-1] in definitions:
                return f"{expr}.map(Into::into)"
            return f"{expr}.map(|v| {convert(ty[7:-1], 'v')})"
        if ty.startswith("Vec<"):
            if ty[4:-1] in definitions:
                return f"{expr}.into_iter().map(Into::into).collect()"
            return f"{expr}.into_iter().map(|v| {convert(ty[4:-1], 'v')}).collect()"
        if ty.startswith("BTreeMap<String, "):
            return f"{expr}.into_iter().map(|(k,v)| (k, {convert(ty[17:-1], 'v')})).collect()"
        return f"{expr}.into()" if ty in definitions else expr

    for name, (kind, fields) in members.items():
        text += f"impl From<wire::{name}> for {name} {{\nfn from(value: wire::{name}) -> Self {{\n"
        if kind == "struct":
            text += "Self {\n" + "\n".join(f"{field}: {convert(ty, 'value.' + field)}," for field, ty in fields) + "\n}\n"
        else:
            text += "match value {\n" + "\n".join(f"wire::{name}::{field}(v) => Self::{field}({convert(ty, 'v')})," for field, ty in fields) + "\n}\n"
        text += "}\n}\n"
    for name in ("Plan", "Registry", "ChainResult", "Event", "ChainError", "StepResult"):
        text += (f"impl crate::Decode for {name} {{\nfn decode(value: serde_json::Value) -> crate::error::Checked<Self> {{\n"
                 f"serde_json::from_value::<wire::{name}>(value).map(Into::into).map_err(|_| crate::Rejection(crate::Code::Schema))\n}}\n}}\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
